"""Security guardrails, policy plugins, and Human-in-the-Loop (HITL) hooks."""

import re
from collections.abc import Mapping
from typing import Any, Final

from google.adk.agents.callback_context import CallbackContext
from google.adk.models.llm_request import LlmRequest
from google.adk.models.llm_response import LlmResponse
from google.adk.plugins.base_plugin import BasePlugin
from google.adk.tools.base_tool import BaseTool
from google.adk.tools.tool_context import ToolContext
from google.genai import types

from journal_agent import observability

logger = observability.configure_structured_logging()

_PROMPT_INJECTION_PATTERNS: Final[tuple[re.Pattern[str], ...]] = (
    re.compile(r"ignore\s+(all\s+)?previous\s+instructions", re.IGNORECASE),
    re.compile(r"system\s+override", re.IGNORECASE),
    re.compile(r"disregard\s+(your\s+)?system\s+prompt", re.IGNORECASE),
    re.compile(
        r"bypass\s+(confirmation|safety|guardrail|human\s+in\s+the\s+loop)",
        re.IGNORECASE,
    ),
)

_CLINICAL_DIAGNOSIS_REQUEST_PATTERNS: Final[tuple[re.Pattern[str], ...]] = (
    re.compile(
        r"\bdiagnose\s+me\s+with\b|\bgive\s+me\s+a\s+(medical|clinical|psychiatric)\s+diagnosis\b",
        re.IGNORECASE,
    ),
    re.compile(
        r"\bprescribe\s+(me\s+)?(medication|antidepressants|pills|drugs)\b",
        re.IGNORECASE,
    ),
)

_PROHIBITED_DIAGNOSTIC_OUTPUT_PATTERNS: Final[tuple[re.Pattern[str], ...]] = (
    re.compile(
        r"\bi\s+diagnose\s+you\s+with\b|\byou\s+are\s+clinically\s+diagnosed\s+with\b",
        re.IGNORECASE,
    ),
    re.compile(
        r"\byour\s+official\s+(medical|psychiatric)\s+diagnosis\s+is\b",
        re.IGNORECASE,
    ),
    re.compile(
        r"\bi\s+am\s+prescribing\s+you\b",
        re.IGNORECASE,
    ),
)

_HIGH_STAKES_EXPORT_TOOLS: Final[frozenset[str]] = frozenset(
    {
        "export_clinician_review_report",
        "export_medical_review_report",
    }
)

_PREVIEW_STATE_KEY: Final[str] = "medical_export_preview_ready"


def _extract_latest_user_text(llm_request: LlmRequest) -> str:
    """Extracts the text of the latest user message in an LlmRequest."""
    if not llm_request.contents:
        return ""
    for content in reversed(llm_request.contents):
        if content.role == "user" and content.parts:
            texts = [part.text for part in content.parts if part.text]
            if texts:
                return "\n".join(texts)
    return ""


def inspect_input_guardrails(user_text: str) -> str | None:
    """Evaluates user input against prompt-injection and clinical-scope policies.

    Args:
        user_text: Raw text submitted by the user.

    Returns:
        A policy refusal message if a guardrail is triggered, or None if the
        input is permitted.
    """
    if not user_text:
        return None

    for pattern in _PROMPT_INJECTION_PATTERNS:
        if pattern.search(user_text):
            logger.warning(
                "Blocked prompt injection attempt",
                extra={
                    "event_type": "guardrail_input_blocked",
                    "structured_data": {"reason": "prompt_injection_detected"},
                },
            )
            return (
                "I cannot fulfill requests to override system instructions or "
                "bypass safety and confirmation controls. I can continue helping "
                "you record journal entries, review emotional patterns, or "
                "prepare a confirmed observational summary."
            )

    for pattern in _CLINICAL_DIAGNOSIS_REQUEST_PATTERNS:
        if pattern.search(user_text):
            logger.warning(
                "Blocked clinical diagnosis or prescription request",
                extra={
                    "event_type": "guardrail_input_blocked",
                    "structured_data": {"reason": "clinical_diagnosis_request"},
                },
            )
            return (
                "I am an observational journaling assistant, not a licensed "
                "medical or mental health professional. I cannot provide a "
                "clinical diagnosis or prescribe medication. However, I can "
                "summarize the emotional states, challenges, and patterns from "
                "your journal entries or prepare an observational report for "
                "you to share with a healthcare professional."
            )

    return None


def evaluate_output_guardrails(model_text: str) -> str | None:
    """Self-evaluates model output to prevent unauthorized diagnostic claims.

    Args:
        model_text: Text generated by the LLM.

    Returns:
        Sanitized replacement text if a prohibited diagnostic claim is found, or
        None if the output passes self-evaluation.
    """
    if not model_text:
        return None

    for pattern in _PROHIBITED_DIAGNOSTIC_OUTPUT_PATTERNS:
        if pattern.search(model_text):
            logger.warning(
                "Output guardrail intercepted prohibited diagnostic statement",
                extra={
                    "event_type": "guardrail_output_rewritten",
                    "structured_data": {
                        "reason": "prohibited_diagnostic_claim"
                    },
                },
            )
            return (
                "Note: As an observational journaling assistant, I cannot make "
                "clinical diagnoses or prescribe treatments. Based solely on "
                "your self-reported journal entries, please consult a qualified "
                "healthcare professional for clinical evaluation."
            )
    return None


def before_model_guardrail(
    callback_context: CallbackContext,
    llm_request: LlmRequest,
) -> LlmResponse | None:
    """ADK before_model_callback enforcing input security and clinical guardrails.

    Args:
        callback_context: Active ADK CallbackContext.
        llm_request: Outgoing LlmRequest about to be sent to Gemini.

    Returns:
        An LlmResponse short-circuiting the model call if blocked by policy, or
        None to proceed normally.
    """
    _ = callback_context
    user_text = _extract_latest_user_text(llm_request)
    refusal = inspect_input_guardrails(user_text)
    if refusal is None:
        return None
    return LlmResponse(
        content=types.Content(
            role="model",
            parts=[types.Part.from_text(text=refusal)],
        )
    )


def after_model_guardrail(
    callback_context: CallbackContext,
    llm_response: LlmResponse,
) -> LlmResponse | None:
    """ADK after_model_callback performing self-evaluation on model outputs.

    Args:
        callback_context: Active ADK CallbackContext.
        llm_response: LlmResponse returned by Gemini.

    Returns:
        A sanitized LlmResponse if prohibited diagnostic claims were detected,
        or None to keep the original response.
    """
    _ = callback_context
    if not llm_response.content or not llm_response.content.parts:
        return None

    combined_text = "\n".join(
        part.text for part in llm_response.content.parts if part.text
    )
    sanitized = evaluate_output_guardrails(combined_text)
    if sanitized is None:
        return None

    return LlmResponse(
        content=types.Content(
            role="model",
            parts=[types.Part.from_text(text=sanitized)],
        )
    )


def before_tool_hook(
    tool: BaseTool,
    args: dict[str, Any],
    tool_context: ToolContext,
) -> dict[str, Any] | None:
    """ADK before_tool_callback recording intent and enforcing HITL stops.

    Args:
        tool: ADK BaseTool being invoked.
        args: Tool arguments supplied by the LLM.
        tool_context: Active ADK ToolContext with session state access.

    Returns:
        A structured stop dictionary if Human-in-the-Loop confirmation rules are
        violated, or None to allow tool execution to proceed.
    """
    tool_name = getattr(tool, "name", str(tool))
    observability.log_tool_intent(
        logger=logger,
        tool_name=tool_name,
        tool_args=args,
    )

    if tool_name in _HIGH_STAKES_EXPORT_TOOLS and bool(
        args.get("user_confirmed", False)
    ):
        state = getattr(tool_context, "state", None)
        preview_ready = (
            bool(state.get(_PREVIEW_STATE_KEY, False))
            if isinstance(state, Mapping) or hasattr(state, "get")
            else False
        )
        if not preview_ready:
            logger.warning(
                "HITL hook blocked unpreviewed export on %s",
                tool_name,
                extra={
                    "event_type": "hitl_gate_blocked",
                    "structured_data": {
                        "tool_name": tool_name,
                        "reason": "preview_not_shown_in_session",
                    },
                },
            )
            return {
                "status": "hitl_confirmation_blocked",
                "message": (
                    "Human-in-the-Loop guardrail: Cannot execute a confirmed "
                    "medical export before generating and showing a preview to "
                    "the user in this session."
                ),
                "recovery_instruction": (
                    f"Call {tool_name} with user_confirmed=False first, show "
                    "the preview to the user, and wait for their explicit "
                    "approval before calling with user_confirmed=True."
                ),
            }

    return None


def after_tool_hook(
    tool: BaseTool,
    args: dict[str, Any],
    tool_context: ToolContext,
    tool_response: dict[str, Any],
) -> dict[str, Any] | None:
    """ADK after_tool_callback recording outcome and updating HITL session state.

    Args:
        tool: Executed ADK BaseTool.
        args: Arguments passed to the tool.
        tool_context: Active ADK ToolContext.
        tool_response: Dictionary returned by the tool execution.

    Returns:
        None (retains the original `tool_response`).
    """
    tool_name = getattr(tool, "name", str(tool))
    outcome_mapping = (
        tool_response
        if isinstance(tool_response, Mapping)
        else {"result": tool_response}
    )
    observability.log_tool_outcome(
        logger=logger,
        tool_name=tool_name,
        tool_args=args,
        outcome=outcome_mapping,
    )

    state = getattr(tool_context, "state", None)
    if state is not None and tool_name in _HIGH_STAKES_EXPORT_TOOLS:
        status = outcome_mapping.get("status")
        if status == "confirmation_required":
            state[_PREVIEW_STATE_KEY] = True
        elif status == "exported":
            state[_PREVIEW_STATE_KEY] = False

    return None


def on_tool_error_hook(
    tool: BaseTool,
    args: dict[str, Any],
    tool_context: ToolContext,
    error: Exception,
) -> dict[str, Any] | None:
    """ADK on_tool_error_callback returning guided recovery instructions to LLM.

    Args:
        tool: ADK BaseTool that raised an exception.
        args: Arguments passed to the tool.
        tool_context: Active ADK ToolContext.
        error: Exception raised during tool execution.

    Returns:
        Structured error dictionary with descriptive recovery instructions.
    """
    _ = tool_context
    tool_name = getattr(tool, "name", str(tool))
    logger.error(
        "Unhandled error in tool %s: %s",
        tool_name,
        error,
        extra={
            "event_type": "tool_error",
            "structured_data": {
                "tool_name": tool_name,
                "tool_args": dict(args),
                "error": str(error),
            },
        },
    )
    return {
        "status": "error",
        "error_type": type(error).__name__,
        "message": f"Tool {tool_name} encountered an error: {error}",
        "recovery_instruction": (
            "Verify the tool arguments against the schema and inform the user "
            "gracefully without exposing internal stack traces."
        ),
    }


class JournalSafetyAndObservabilityPlugin(BasePlugin):
    """App-level ADK plugin enforcing safety guardrails, HITL, and telemetry."""

    def __init__(self, name: str = "journal_safety_and_observability") -> None:
        """Initializes the instance.

        Args:
            name: Unique identifier for the plugin instance.
        """
        super().__init__(name=name)

    async def before_model_callback(
        self,
        *,
        callback_context: CallbackContext,
        llm_request: LlmRequest,
    ) -> LlmResponse | None:
        """Runs input guardrails before every LLM request."""
        return before_model_guardrail(callback_context, llm_request)

    async def after_model_callback(
        self,
        *,
        callback_context: CallbackContext,
        llm_response: LlmResponse,
    ) -> LlmResponse | None:
        """Runs output self-evaluation guardrails after every LLM response."""
        return after_model_guardrail(callback_context, llm_response)

    async def before_tool_callback(
        self,
        *,
        tool: BaseTool,
        tool_args: dict[str, Any],
        tool_context: ToolContext,
    ) -> dict[str, Any] | None:
        """Logs tool intent and enforces the HITL confirmation checkpoint."""
        return before_tool_hook(tool, tool_args, tool_context)

    async def after_tool_callback(
        self,
        *,
        tool: BaseTool,
        tool_args: dict[str, Any],
        tool_context: ToolContext,
        result: dict[str, Any],
    ) -> dict[str, Any] | None:
        """Logs tool outcome and updates HITL preview state."""
        return after_tool_hook(tool, tool_args, tool_context, result)

    async def on_tool_error_callback(
        self,
        *,
        tool: BaseTool,
        tool_args: dict[str, Any],
        tool_context: ToolContext,
        error: Exception,
    ) -> dict[str, Any] | None:
        """Provides guided error recovery when a tool raises an exception."""
        return on_tool_error_hook(tool, tool_args, tool_context, error)
